import { spawnSync } from 'child_process'
import fs from 'fs'
import os from 'os'
import path from 'path'
import { fileURLToPath } from 'url'

const projectDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const chafa = process.env.CHAFA_BIN || 'chafa'
const states = ['idle', 'walk', 'attack', 'dead']
const sprites = {}
const temporaryDir = fs.mkdtempSync(path.join(os.tmpdir(), 'aleph-rogue-sprites-'))

try {
  for (const state of states) {
    const input = path.join(projectDir, 'fixtures', `${state}.gif`)
    const frameCount = countFrames(input)
    sprites[state] = []

    for (let index = 0; index < frameCount; index++) {
      const frame = path.join(temporaryDir, `${state}-${index}.png`)

      run('magick', [
        `${input}[${index}]`,
        '-fuzz', '18%',
        '-transparent', '#00ff00',
        '-trim',
        '+repage',
        frame
      ])

      const ansi = run(chafa, [
        '--format', 'symbols',
        '--size', '8x6',
        '--stretch',
        '--colors', '16',
        '--symbols', 'block+border+space',
        frame
      ])

      sprites[state].push(normalizeFrame(ansi))
    }
  }

  const output = [
    '// Generated by scripts/build-ansi-sprites.mjs using Chafa.',
    '// Do not edit manually.',
    `export const ANSI_SPRITES = ${JSON.stringify(sprites, null, 2)}`,
    ''
  ].join('\n')

  fs.writeFileSync(path.join(projectDir, 'game', 'ansi-sprites.mjs'), output)
  console.log('Generated game/ansi-sprites.mjs')
} finally {
  fs.rmSync(temporaryDir, { recursive: true, force: true })
}

function countFrames (input) {
  const output = run('identify', ['-format', '%n\n', input])
  const count = Number.parseInt(output, 10)
  if (!Number.isInteger(count) || count < 1) throw new Error(`No frames in ${input}`)
  return count
}

function normalizeFrame (ansi) {
  const lines = ansi
    .replaceAll('\r', '')
    .split('\n')
    .filter(Boolean)

  while (lines.length < 4) lines.push('    ')
  return lines.slice(0, 4)
}

function run (command, args) {
  const result = spawnSync(command, args, { encoding: 'utf8' })

  if (result.error) throw result.error
  if (result.status !== 0) {
    throw new Error(`${command} failed: ${result.stderr.trim()}`)
  }

  return result.stdout
}
